texts  = [t for d, t in training_data]
labels = [d for d, t in training_data]

le = LabelEncoder()
y  = le.fit_transform(labels)

print('Departments: %d' % len(le.classes_))
for c in le.classes_:
    n = sum(1 for l in labels if l == c)
    print('  %-30s: %d samples' % (c, n))
print('Total: %d samples\n' % len(texts))

vectorizer = TfidfVectorizer(
    ngram_range=(1, 2), min_df=2, max_df=0.95,
    sublinear_tf=True, strip_accents='unicode',
    analyzer='word', max_features=25000
)
X = vectorizer.fit_transform(texts)
print('Vocab size: %d\n' % X.shape[1])

print('Running 5-fold cross-validation...')
skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
pipeline_cv = Pipeline([
    ('tfidf', TfidfVectorizer(ngram_range=(1,2), min_df=2, max_df=0.95,
                              sublinear_tf=True, analyzer='word', max_features=25000)),
    ('clf',   LinearSVC(C=0.4, max_iter=5000, class_weight='balanced'))
])
cv_acc = cross_val_score(pipeline_cv, texts, y, cv=skf, scoring='accuracy')
cv_f1  = cross_val_score(pipeline_cv, texts, y, cv=skf, scoring='f1_macro')
print('CV per fold: %s' % [round(v*100,1) for v in cv_acc])
print('CV mean=%.1f%%  std=%.1f%%' % (cv_acc.mean()*100, cv_acc.std()*100))
if cv_acc.mean() < 0.60:
    print('STATUS: Low accuracy')
elif cv_acc.std() > 0.10:
    print('STATUS: High variance - possible overfit')
else:
    print('STATUS: Healthy - no overfit/underfit\n')

print('Training final calibrated model...')
model = CalibratedClassifierCV(
    LinearSVC(C=0.4, max_iter=5000, class_weight='balanced'),
    cv=5, method='sigmoid'
)
model.fit(X, y)

y_in   = model.predict(X)
in_acc = accuracy_score(y, y_in) * 100

y_cv_pred  = cross_val_predict(pipeline_cv, texts, y, cv=skf)
cv_overall = accuracy_score(y, y_cv_pred) * 100
rpt = classification_report(y, y_cv_pred, target_names=le.classes_, output_dict=True)

print()
print('='*65)
print('  MODEL ACCURACY REPORT — 12 DEPARTMENTS (100 samples each)')
print('='*65)
print('Cross-Val Accuracy : %.1f%%' % cv_overall)
print('CV F1-Macro        : %.1f%%' % (cv_f1.mean()*100))
print('In-sample Accuracy : %.1f%%' % in_acc)
print()
print('%-30s  Prec   Recall   F1    Correct/100' % 'Department')
print('-'*65)
for dept in le.classes_:
    r  = rpt[dept]
    n  = int(r['support'])
    tp = int(round(r['recall'] * n))
    print('%-30s  %.2f    %.2f    %.2f    %d/%d' % (
        dept, r['precision'], r['recall'], r['f1-score'], tp, n))

